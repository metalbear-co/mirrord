//! `mirrord preview up`: starts a preview environment for every service of a `mirrord-up.yaml`
//! that has an image, all under one key, and returns once each one is ready, idle or failed.
//!
//! Every service's session is created the way `mirrord preview start` creates one, from the
//! config `mirrord_up::resolve_preview_services` assembles for it. All sessions are prepared
//! first, and none is started unless every one passed its checks, so an invalid service never
//! leaves the others replaced. A session that fails to start doesn't stop the others.

use std::{io::ErrorKind, ops::Not, path::Path, sync::Arc};

use futures::future::join_all;
use mirrord_analytics::{AnalyticsReporter, ExecutionKind};
use mirrord_config::{
    config::{ConfigContext, EnvKey},
    env_key::MIRRORD_ENV_KEY,
    feature::{database_branches::DatabaseBranchesConfig, split_queues::SplitQueuesConfig},
    util::GIT_BRANCH,
};
use mirrord_operator::crd::NewOperatorFeature;
use mirrord_progress::{Progress, ProgressTracker};
use mirrord_up::{SubprocessCfg, UpError, load_up_config, preview_image_env};

use super::{
    PreparedPreview, create_preview_api, load_manifests, manifest_sources, target_namespace,
};
use crate::{
    config::{DEFAULT_PREVIEW_CONFIG_FILE, ManifestSourceArgs, PreviewCommonArgs, PreviewUpArgs},
    data::{GlobalConfig, UserData},
    error::{CliError, CliResult},
};

/// Handle `mirrord preview up`.
pub(super) async fn preview_up(
    common: &PreviewCommonArgs,
    args: PreviewUpArgs,
    watch: drain::Watch,
    user_data: &UserData,
) -> CliResult<()> {
    let mut progress = ProgressTracker::from_env("mirrord preview up");

    let key = match findable_key(common.key.as_deref()) {
        Some(key) => EnvKey::Provided(key),
        None => EnvKey::Generated(EnvKey::autogenerated()),
    };
    progress.info(&format!("key: {}", key.as_str()));

    // `-f` is shared with the other `preview` subcommands, where a bare `-f` stands for a
    // mirrord config, which is never a valid `mirrord-up.yaml`.
    let path = match common.config_file.as_deref() {
        Some(path) if path != Path::new(DEFAULT_PREVIEW_CONFIG_FILE) => path,
        _ => Path::new("mirrord-up.yaml"),
    };
    let mut up_config = match load_up_config(path, &key) {
        Err(UpError::Io(error)) if error.kind() == ErrorKind::NotFound => {
            return Err(CliError::PreviewUpFileNotFound(path.to_owned()));
        }
        result => result?,
    };
    up_config.default_context(GlobalConfig::load().await.kube_context().map(Arc::from));

    let images = up_config.select_preview_images(&args.image)?;
    for service in &images.skipped {
        progress.info(&format!(
            "{service}: no image (`--image {service}=<image ref>` or `{}`), skipped",
            preview_image_env(service)
        ));
    }

    let mut services = mirrord_up::resolve_preview_services(
        up_config,
        path,
        common.context.as_deref().map(Arc::from),
        &key,
    )
    .await?;
    services.sort_by(|a, b| a.service_name.cmp(&b.service_name));

    let args = &args;
    let prepared = join_all(services.into_iter().map(|service| {
        let name = service.service_name.clone();
        let progress = progress.subtask(&name).prefixed(&name);
        let watch = watch.clone();
        async move {
            let result = prepare_service(service, args, &progress, watch, user_data).await;
            (name, progress, result)
        }
    }))
    .await;

    let mut failed = Vec::new();
    let mut checked = Vec::new();
    for (name, mut service_progress, result) in prepared {
        match result {
            Ok(preview) => checked.push((name, service_progress, preview)),
            Err(error) => {
                service_progress.failure(Some(&error.to_string()));
                failed.push(name.to_string());
            }
        }
    }

    let same_target = |a: &PreparedPreview, b: &PreparedPreview| {
        a.layer_config.kube_context == b.layer_config.kube_context
            && target_namespace(&a.operator_api, &a.layer_config)
                == target_namespace(&b.operator_api, &b.layer_config)
            && a.session_target == b.session_target
    };
    let clashes = checked
        .iter()
        .enumerate()
        .map(|(index, (_, _, preview))| {
            checked
                .iter()
                .enumerate()
                .find(|(other_index, (_, _, other))| {
                    *other_index != index && same_target(preview, other)
                })
                .map(|(_, (other, ..))| other.clone())
        })
        .collect::<Vec<_>>();

    let mut ready_to_start = Vec::new();
    for ((name, mut service_progress, preview), clash) in checked.into_iter().zip(clashes) {
        match clash {
            Some(other) => {
                service_progress.failure(Some(&format!(
                    "has the same target as `{other}`: sessions under one key and target \
                     replace each other"
                )));
                failed.push(name.to_string());
            }
            None => ready_to_start.push((name, service_progress, preview)),
        }
    }
    failed.sort();

    if failed.is_empty().not() {
        for (_, mut service_progress, _) in ready_to_start {
            service_progress.failure(Some("not started"));
        }
        progress.failure(Some("no preview environment was started"));
        return Err(CliError::PreviewUpInvalid(failed));
    }

    let started = join_all(ready_to_start.into_iter().map(
        |(name, mut service_progress, preview)| async move {
            let result = preview.start(&mut service_progress).await;
            (name, service_progress, result)
        },
    ))
    .await;

    for (name, mut service_progress, result) in started {
        match result {
            Ok(summary) => {
                service_progress
                    .subtask(&format!("key: {}", summary.key))
                    .success(None);
                service_progress
                    .subtask(&format!("namespace: {}", summary.namespace))
                    .success(None);
                service_progress
                    .subtask(&format!("session: {}", summary.session_name))
                    .success(None);
                if let Some(share_host) = summary.share_host {
                    service_progress
                        .subtask(&format!("preview URL: https://{share_host}"))
                        .success(None);
                }
                service_progress.success(Some(if summary.idle {
                    "preview environment is idle"
                } else {
                    "preview environment is ready"
                }));
            }
            Err(error) => {
                service_progress.failure(Some(&error.to_string()));
                failed.push(name.to_string());
            }
        }
    }

    if failed.is_empty().not() {
        progress.failure(Some("some preview environments failed to start"));
        return Err(CliError::PreviewUpFailed(failed));
    }

    progress.success(Some("preview environments are up"));
    Ok(())
}

/// Applies the run's flags to one service's config and runs every check that doesn't change the
/// cluster, dropping the defaults `mirrord up` added that its operator can't serve.
async fn prepare_service(
    service: SubprocessCfg,
    args: &PreviewUpArgs,
    progress: &ProgressTracker,
    watch: drain::Watch,
    user_data: &UserData,
) -> CliResult<PreparedPreview> {
    let SubprocessCfg {
        mut config,
        default_db_branches,
        default_split_queues,
        ..
    } = service;

    // Set over the patched config, so they take precedence over the service's `config_patch`.
    if let Some(ttl) = args.ttl {
        config.feature.preview.ttl_mins = Some(ttl);
        config.feature.preview.ttl_secs = None;
    }
    if let Some(timeout) = args.timeout {
        config.feature.preview.creation_timeout_secs = timeout;
    }

    if let Some(target) = &config.target.path {
        progress.info(&format!("target: {target}"));
    }

    // `mirrord up` assembles the config without it, so the preview checks below would take
    // the presets for options the user set.
    config.apply_magic();

    let mut context = ConfigContext::default().strict_env(true);
    let verified = config.verify_for_preview_env(&mut context);
    for warning in context.into_warnings() {
        progress.warning(&warning);
    }
    verified?;

    let sources = manifest_sources(ManifestSourceArgs::default(), &mut config);
    let supplied_objects = if sources.paths.is_empty() {
        None
    } else {
        Some(load_manifests(&sources.paths, progress)?)
    };

    let mut analytics = AnalyticsReporter::only_error(
        config.telemetry,
        ExecutionKind::Preview,
        watch,
        user_data.machine_id(),
        Some(config.key.as_str().to_owned()),
    );
    let (operator_api, api) = create_preview_api(&config, false, progress, &mut analytics).await?;

    // A request the user set fails in `prepare` instead, as it does for `mirrord preview start`.
    if default_db_branches
        && operator_api
            .operator()
            .spec
            .supported_features()
            .contains(&NewOperatorFeature::DbBranchesFromSplitConfig)
            .not()
    {
        progress.warning(
            "the mirrord operator doesn't support DB branching, running against the source DB",
        );
        config.feature.db_branches = DatabaseBranchesConfig::default();
    }
    // The operator fails a preview session over a queue split it can't serve, instead of
    // dropping it as it does for `mirrord up` sessions, so the splits `mirrord up` adds by
    // default can't be sent.
    if default_split_queues {
        progress.warning(
            "queues are not split: the mirrord operator can't split them by default for preview \
             environments",
        );
        config.feature.split_queues = SplitQueuesConfig::default();
    }

    PreparedPreview::prepare(
        config,
        operator_api,
        api,
        &sources,
        supplied_objects,
        progress,
    )
    .await
}

/// The key `mirrord preview up` runs under when it can be found again: `--key`, then
/// `MIRRORD_KEY`, then the branch (`GITHUB_HEAD_REF` in a GitHub pull request, otherwise the
/// current git branch). `None` on `main`, `master` or without a branch.
fn findable_key(arg: Option<&str>) -> Option<String> {
    let set = |value: &String| value.is_empty().not();

    arg.map(ToOwned::to_owned)
        .or_else(|| std::env::var(MIRRORD_ENV_KEY).ok().filter(set))
        .or_else(|| {
            std::env::var("GITHUB_HEAD_REF")
                .ok()
                .filter(set)
                .or_else(|| GIT_BRANCH.clone())
                .filter(|branch| matches!(branch.as_str(), "main" | "master").not())
        })
}
