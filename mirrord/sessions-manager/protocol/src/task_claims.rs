//! Selecting the tasks of a service by what they are tagged with, rather than by replica id.
//!
//! A developer's `mirrord up` holds a **claim** open on the sessions-manager for as long as its
//! session lives: a filter over task tags. Every starting task's agent asks the sessions-manager
//! for **admission** with the tags of its task. The sessions-manager offers the task to the
//! claims of its scope and tells the claim that takes it which replica to connect to, so that
//! `mirrord up` can start a local process for exactly that task.
//!
//! Tags travel in request bodies only. They describe the customer's workload, and URLs end up in
//! access logs.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};
use strum_macros::{AsRefStr, EnumString};
use uuid::Uuid;

use crate::{ReplicaId, control_plane::string_id};

/// Key of the tag that binds a task to one session: a task tagged `mirrord-key=<session key>` is
/// offered only to the claim of the session with that key, whatever any claim's filter says.
pub const MIRRORD_KEY_TAG: &str = "mirrord-key";

string_id!(
    /// Identifies one claim across reconnects of its subscription: a UUID generated by the
    /// client. Registering a claim under an id that is still registered replaces the older
    /// registration.
    ClaimId
);
string_id!(
    /// Identifies one task taken by one claim.
    MatchId
);

/// Sent by the developer's `mirrord up` to register a claim, as the body of the request whose
/// response streams the claim's events.
///
/// A sessions-manager refuses a registration with a field it does not know, instead of ignoring
/// the field: every field changes which tasks the claim takes or what happens to them, and a
/// client has no other way to learn that an older sessions-manager did not honor one. A client
/// therefore leaves out the fields it does not use, so that it keeps working with a
/// sessions-manager that predates them.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ClaimRegistration {
    pub claim_id: ClaimId,
    /// Key of the developer's session. The claim takes every task tagged with it under
    /// [`MIRRORD_KEY_TAG`], with or without a filter.
    pub session_key: String,
    /// Tag names mapped to regexes. A task matches when it has every named tag with a value
    /// matching its regex. An empty map matches every task.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tag_filter: Option<BTreeMap<String, String>>,
    /// A jq program run on `{"tags": {"<key>": "<value>", ...}}`. A task matches when the
    /// program outputs `true`. Combined with `tag_filter`, a task must match both.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub jq_filter: Option<String>,
}

/// Names of the SSE events sessions-manager sends over a claim's subscription.
///
/// A client skips an event whose name it does not know: a newer sessions-manager may send events
/// this build has no use for.
#[derive(Clone, Copy, Debug, PartialEq, Eq, AsRefStr, EnumString)]
#[strum(serialize_all = "snake_case")]
pub enum ClaimEventName {
    /// Carries a [`TaskMatched`] as its JSON body.
    Matched,
    /// Carries an empty body. The claim's jq program ran past the sessions-manager's time limit,
    /// and the claim was removed. Always the last event of the subscription.
    FilterTimedOut,
    /// Carries an empty body; signals that a newer registration of the same claim replaced this
    /// subscription. Always the last event of the subscription.
    Superseded,
}

/// A task the claim took. Its agent is registered, or about to register, under `replica_id` in
/// the claim's scope.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct TaskMatched {
    pub match_id: MatchId,
    pub replica_id: ReplicaId,
}

/// Sent by a task's agent when the task starts, to offer the task to the claims of its scope.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct AdmissionRequest {
    pub replica_id: ReplicaId,
    pub agent_instance_id: Uuid,
    pub tags: BTreeMap<String, String>,
}

/// The sessions-manager's answer to an [`AdmissionRequest`].
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct AdmissionResponse {
    pub verdict: AdmissionVerdict,
}

/// What a task does after asking for admission.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AdmissionVerdict {
    /// The task runs its own code, whether or not a claim took it.
    Continue,
    /// A verdict this build does not know, which a task treats as [`Self::Continue`]: running
    /// its own code is what it would have done without mirrord.
    #[serde(other)]
    Unknown,
}
